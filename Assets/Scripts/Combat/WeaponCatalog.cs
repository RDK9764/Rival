using System;
using System.Collections.Generic;
using UnityEngine;

namespace Rival.Combat
{
    /// <summary>
    /// One weapon paired with its attack chain, addressable by a plain string id.
    /// Kept as a serialized reference so the loadout can swap equipment at
    /// runtime without any disk/Resources load.
    /// </summary>
    [Serializable]
    public class WeaponCatalogEntry
    {
        [Tooltip("Plain id used by the loadout system (e.g. \"Sword\"). Matches WeaponName.")]
        public string id;
        public Weapon weapon;
        public AttackDefinition[] comboChain;
    }

    /// <summary>
    /// All selectable weapons + their attack chains in one place. The loadout
    /// manager resolves a weapon by id from here and hands it to the player's
    /// CombatController via Equip. Generated by the editor WeaponFactory.
    /// </summary>
    [CreateAssetMenu(menuName = "Rival/Combat/Weapon Catalog", fileName = "WeaponCatalog")]
    public class WeaponCatalog : ScriptableObject
    {
        [SerializeField] private List<WeaponCatalogEntry> entries = new List<WeaponCatalogEntry>();

        public IReadOnlyList<WeaponCatalogEntry> Entries => entries;

        public WeaponCatalogEntry Find(string id)
        {
            if (string.IsNullOrEmpty(id)) return null;
            foreach (var entry in entries)
            {
                if (entry != null && string.Equals(entry.id, id, StringComparison.OrdinalIgnoreCase))
                    return entry;
            }
            return null;
        }
    }
}
